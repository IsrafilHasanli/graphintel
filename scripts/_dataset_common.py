"""Shared constants and helpers for the GraphIntel dataset pipeline.

Everything here is deterministic and stdlib-only so the demo dataset can be
regenerated byte-for-byte on any machine with no network and no dependencies.
"""
from __future__ import annotations

import json
from datetime import UTC, date, datetime, timedelta
from pathlib import Path

# Repo layout ---------------------------------------------------------------
REPO_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = REPO_ROOT / "data"
RAW_DIR = DATA_DIR / "raw"
SYNTHETIC_DIR = DATA_DIR / "synthetic"
PROCESSED_DIR = DATA_DIR / "processed"
FIXTURES_DIR = DATA_DIR / "fixtures"
# Source-shaped files the ingestion pipeline consumes.
IMPORT_DIR = PROCESSED_DIR / "import"

# Determinism anchors -------------------------------------------------------
# All relative time expressions ("last 30 days") in the demo and in evaluation
# are computed against this fixed reference "now" so results are reproducible.
DATASET_REFERENCE_DATE = date(2026, 9, 21)
GENERATOR_SCRIPT = "generate_synthetic_demo_data.py"

# Minimum counts the dataset must satisfy (mirrors docs/DATASET_PLAN.md).
MINIMUM_COUNTS = {
    "customers": 5,
    "support_tickets": 50,
    "incidents": 10,
    "incident_updates": 20,
    "postmortems": 5,
    "services": 8,
    "teams": 4,
    "sla_contracts": 5,
    "sla_clauses": 15,
    "runbooks": 5,
    "relations": 20,
}


def reference_now() -> datetime:
    """The pinned 'now' as a timezone-aware UTC datetime."""
    return datetime.combine(DATASET_REFERENCE_DATE, datetime.min.time(), tzinfo=UTC)


def days_ago(n: int) -> str:
    """ISO-8601 timestamp `n` days before the reference date."""
    return (reference_now() - timedelta(days=n)).isoformat()


def synthetic_meta(source_rule: str) -> dict:
    """Provenance stamp required on every synthetic record."""
    return {
        "synthetic": True,
        "source_rule": source_rule,
        "created_by_script": GENERATOR_SCRIPT,
    }


def ensure_dirs() -> None:
    for d in (RAW_DIR, SYNTHETIC_DIR, PROCESSED_DIR, FIXTURES_DIR, IMPORT_DIR):
        d.mkdir(parents=True, exist_ok=True)


def write_json(path: Path, payload: object) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    return path


def read_json(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def write_text(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path
